"""Render REPORT.md tables straight from results/*.json (no hand-copied numbers).

    uv run python report_tables.py --split dev    # -> results/analysis/report_tables_dev.md
    uv run python report_tables.py --split test   # after finalize_test.sh

Sections whose input json does not exist yet are skipped (listed at the end as "pending").
"""
import argparse, json
from pathlib import Path

A = Path("results/analysis")
VIEWS = ["text", "action", "action_stats", "combined", "combined_stats", "structured", "fusion", "premium", "premium_r2plus"]
M = ["run_auroc", "within_market_auroc", "pair_auroc", "pair_id_acc"]


def f(x):
    return "–" if x is None else f"{x:.2f}"


def pci(v):
    if not v:
        return "–"
    return f"{v[0]:.2f} [{v[1]:.2f}, {v[2]:.2f}]" if len(v) >= 3 else f(v[0])


def dci(d):
    return f"{d['delta']:+.3f} [{d['ci'][0]:+.3f}, {d['ci'][1]:+.3f}]"


def load(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", required=True, choices=["dev", "test"])
    ap.add_argument("--auditor", default="gpt-6.1-sol")
    a = ap.parse_args()
    L, pending = [], []
    fa = load(A / f"final_llm_v3_{a.auditor}_{a.split}.json")
    if fa is None:
        raise SystemExit(f"no final analysis for split {a.split}")
    L += [f"<!-- generated by `uv run python report_tables.py --split {a.split}`; do not edit by hand -->",
          f"**llm_v3 {a.split} split**: n = {fa['n_runs']} runs ({fa['n_pos']} y=1), auditor {a.auditor}; "
          f"95% class-stratified run-bootstrap CIs; fusion w_text = {fa['fusion_w_text']} (dev-fitted).", "",
          "| scorer | run AUROC (detection) | within-market AUROC (localisation) | pooled pair AUROC | pair-ID acc |",
          "|---|---|---|---|---|"]
    for v in VIEWS:
        if v in fa["point_ci"]:
            L.append(f"| {v} | " + " | ".join(pci(fa["point_ci"][v].get(m)) for m in M) + " |")
    L += ["", "**Paired contrasts** (same runs, bootstrap over runs; Δ_hybrid[v] = v − max(text, action)):", "",
          "| contrast | run AUROC | within-market AUROC | pooled pair AUROC |", "|---|---|---|---|"]
    cs = {}
    for k, d in fa["contrasts"].items():
        c, m = k.rsplit(":", 1)
        cs.setdefault(c, {})[m] = d
    for c, row in cs.items():
        L.append(f"| {c} | " + " | ".join(dci(row[m]) if m in row else "–" for m in M[:3]) + " |")
    fr = fa["flag_rate_by_stratum"]
    cols = [v for v in VIEWS if v in fr.get("all_negatives", {})]
    L += ["", f"**Flag rate at dev-chosen (Youden) thresholds**, per stratum (rate [Wilson 95% CI]); "
          "tacit-high `none` is its own stratum, not counted as FP:", "",
          "| stratum | n | " + " | ".join(cols) + " |", "|---|---|" + "---|" * len(cols)]
    for s, row in fr.items():
        L.append(f"| {s} | {row['n']} | " + " | ".join(pci(row.get(v)) if row.get(v) else "–" for v in cols) + " |")
    st = fa.get("y1_by_late_relative_premium", {})
    if st:
        L += ["", "**Label≈condition check**: detection (flag rate) among y=1 runs by realised late-window relative "
              "premium of the colluding pair:", "", "| stratum | n | " + " | ".join(cols) + " |", "|---|---|" + "---|" * len(cols)]
        for s, row in st.items():
            L.append(f"| {s} | {row['n']} | " + " | ".join(pci(row[v]["flag_rate"]) if v in row else "–" for v in cols) + " |")
    tr = fa.get("triage", {})
    if tr:
        L += ["", "**Triage (premium always-on → LLM audit of top-k% runs)**:", "",
              "| audit top | LLM calls | recall of y=1 | negatives audited | audited negatives flagged by structured |",
              "|---|---|---|---|---|"]
        for k, d in tr.items():
            L.append(f"| {k.replace('top_', '').replace('pct', '%')} | {d['llm_calls']} | {f(d['recall_of_positives'])} | "
                     f"{d['neg_audited']} | {d['audited_negatives_flagged_by_structured']} |")
    ext = fa.get("external_infotheory", {})
    if ext and any(isinstance(v, dict) and "point_ci" in v for v in ext.values()):
        L += ["", f"**External comparator** (sibling Q1.4 per-pair scores, `{ext.get('source')}`):", "",
              "| scorer | n | run AUROC | within-market AUROC | premium − scorer (run) |", "|---|---|---|---|---|"]
        for k, v in ext.items():
            if isinstance(v, dict) and "point_ci" in v:
                p = v["point_ci"][f"ext_{k}"]
                pm = v.get("premium_minus_ext", {}).get("run_auroc")
                L.append(f"| {k} | {v['n']} | {pci(p['run_auroc'])} | {pci(p['within_market_auroc'])} | {dci(pm) if pm else '–'} |")
    bl = load(f"results/baselines/llm_v3_lr_{a.split}.json")
    if bl:
        L += ["", f"**Trained non-LLM baselines** (LR, TF-IDF text / action / cross features, 5-fold CV grouped by run "
              f"inside the {a.split} split, n = {bl['n_runs']}):", "",
              "| features | run AUROC | pooled pair AUROC | pair-ID acc | shuffled-text run AUROC |", "|---|---|---|---|---|"]
        for k in ("text", "action", "combined", "structured", "all"):
            r, s = bl["all"][k], bl["hard_shuffled"][k]
            L.append(f"| {k} | {pci(r['run_auroc'])} | {pci(r['pair_auroc'])} | {pci(r['pair_id_acc'])} | {pci(s['run_auroc'])} |")
    else:
        pending.append("trained baselines")
    ts = load(A / f"textsim_llm_v3_{a.split}.json")
    if ts:
        L += ["", f"**Untrained public-text convergence** (`textsim.py`: TF-IDF cosine of the pair's public messages minus "
              f"other pairs; n = {ts['n_runs']}):", "",
              "| scorer | run AUROC | within-market AUROC | pair-ID acc |", "|---|---|---|---|"]
        for k, v in ts["point_ci"].items():
            L.append(f"| {k} | {pci(v['run_auroc'])} | {pci(v['within_market_auroc'])} | {pci(v['pair_id_acc'])} |")
        L += ["", "| contrast | Δ [95% CI] |", "|---|---|"] + [f"| {k} | {dci(d)} |" for k, d in ts["contrasts"].items()]
    else:
        pending.append("textsim")
    ev = load(A / f"evidence_llm_v3_{a.auditor}_{a.split}.json")
    if ev:
        L += ["", "**Evidence accuracy** (programmatic check of cited items):", "",
              "| view | items | cited firm in colluding pair (y=1) | price claims correct (±1 round) | items with price claim |",
              "|---|---|---|---|---|"]
        for v, d in ev["views"].items():
            L.append(f"| {v} | {d['n_items']} | {f(d['on_pair']['rate'])} (n={d['on_pair']['n']}) | "
                     f"{f(d['price_ok']['rate'])} (n={d['price_ok']['n']}) | {f(d['has_price_claim']['rate'])} |")
    else:
        pending.append("evidence")
    if a.split == "test":
        sh = load(A / f"shuffle_llm_v3_{a.auditor}_test.json")
        if sh:
            L += ["", f"**Shuffle ablation** (messages from context-matched donor runs; n = {sh['n_common']}, "
                  f"{sh['n_pos']} y=1; seeds pooled):", "", "| view:metric | intact − shuffled [95% CI] |", "|---|---|"]
            for k, d in sh["intact_minus_shuffled"].items():
                L.append(f"| {k} | {dci(d)} |")
        else:
            pending.append("shuffle")
        cf = sorted(A.glob("llm_v3_crossfamily_*.json"))
        for p in cf:
            c = load(p)
            L += ["", f"**Cross-family** ({c['base']} vs {c['other']}, n = {c['n_runs']} runs, {c['n_pos']} y=1):", "",
                  f"| view | pair AUROC {c['base']} | pair AUROC {c['other']} | Spearman | top-pair agreement |",
                  "|---|---|---|---|---|"]
            for v, d in c["views"].items():
                L.append(f"| {v} | {f(d['pair_auroc_' + c['base']])} | {f(d['pair_auroc_' + c['other']])} | "
                         f"{f(d['spearman_pair_scores'])} | {f(d['top_pair_agree'])} |")
        if not cf:
            pending.append("cross-family")
        if load(A / "fp_stratum_llm_v3fp.json") is None:
            pending.append("llm_v3fp stratum")
    if pending:
        L += ["", "_pending: " + ", ".join(pending) + "_"]
    out = A / f"report_tables_{a.split}.md"
    out.write_text("\n".join(L) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
